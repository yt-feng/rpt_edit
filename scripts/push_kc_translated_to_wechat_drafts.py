def post_wechat_json(
    session: requests.Session,
    url: str,
    payload: dict[str, Any],
    timeout: int,
    max_attempts: int = WECHAT_REQUEST_MAX_ATTEMPTS,
) -> requests.Response:
    body = json.dumps(payload, ensure_ascii=False, separators=(",", ":")).encode("utf-8")
    max_attempts = max(1, max_attempts)
    label = "wechat/json"

    for attempt in range(1, max_attempts + 1):
        try:
            response = session.post(
                url,
                data=body,
                headers={"Content-Type": "application/json; charset=utf-8"},
                timeout=timeout,
            )
        except requests.RequestException as exc:
            if attempt >= max_attempts:
                raise WeChatError(f"{label} request failed after {max_attempts} attempt(s): {exc}") from exc
            sleep_before_wechat_retry(label, attempt, max_attempts, str(exc))
            continue

        if is_retryable_wechat_response(response) and attempt < max_attempts:
            sleep_before_wechat_retry(label, attempt, max_attempts, f"HTTP {response.status_code}")
            continue
        retryable_error = retryable_wechat_json_error(response)
        if retryable_error and attempt < max_attempts:
            sleep_before_wechat_retry(label, attempt, max_attempts, retryable_error)
            continue
        return response

    raise WeChatError(f"{label} request failed after {max_attempts} attempt(s)")


def get_stable_access_token(session: requests.Session, appid: str, secret: str, timeout: int) -> str:
    response = post_wechat_json(
        session,
        "https://api.weixin.qq.com/cgi-bin/stable_token",
        {"grant_type": "client_credential", "appid": appid, "secret": secret, "force_refresh": False},
        timeout,
        max_attempts=WECHAT_REQUEST_MAX_ATTEMPTS,
    )
    data = parse_wechat_json(response, "stable_token")
    token = data.get("access_token")
    if not token:
        raise WeChatError(f"stable_token did not return access_token: {data}")
    return str(token)


def parse_wechat_json(response: requests.Response, label: str) -> dict[str, Any]:
    try:
        data = response.json()
    except Exception as exc:
        snippet = normalize_space(response.text[:300])
        detail = f": {snippet}" if snippet else ""
        raise WeChatError(f"{label} returned non-JSON response: HTTP {response.status_code}{detail}") from exc
    errcode = data.get("errcode")
    if errcode not in (None, 0):
        raise WeChatError(
            f"{label} failed: errcode={errcode} errmsg={data.get('errmsg')}",
            errcode=int(errcode) if isinstance(errcode, int) or str(errcode).isdigit() else None,
            errmsg=str(data.get("errmsg") or ""),
        )
    return data


def is_retryable_wechat_response(response: requests.Response) -> bool:
    return response.status_code in WECHAT_RETRYABLE_STATUS_CODES or 500 <= response.status_code < 600


def retryable_wechat_json_error(response: requests.Response) -> str:
    try:
        data = response.json()
    except Exception:
        return ""
    errcode = data.get("errcode")
    if errcode in WECHAT_RETRYABLE_ERRCODES:
        return f"errcode={errcode} errmsg={data.get('errmsg')}"
    return ""


def retry_delay_seconds(attempt: int) -> float:
    delay = WECHAT_REQUEST_RETRY_BASE_SECONDS * (2 ** max(0, attempt - 1))
    return min(WECHAT_REQUEST_RETRY_MAX_SECONDS, delay)


def sleep_before_wechat_retry(label: str, attempt: int, max_attempts: int, reason: str) -> None:
    delay = retry_delay_seconds(attempt)
    log(f"{label}: attempt {attempt}/{max_attempts} failed ({reason}); retrying in {delay:.1f}s")
    time.sleep(delay)


def upload_wechat_file(
    session: requests.Session,
    url: str,
    path: Path,
    label: str,
    timeout: int,
) -> dict[str, Any]:
    mime = mimetypes.guess_type(path.name)[0] or "application/octet-stream"
    max_attempts = WECHAT_REQUEST_MAX_ATTEMPTS

    for attempt in range(1, max_attempts + 1):
        try:
            with path.open("rb") as handle:
                response = session.post(url, files={"media": (path.name, handle, mime)}, timeout=timeout)
        except requests.RequestException as exc:
            if attempt >= max_attempts:
                raise WeChatError(
                    f"{label} upload failed after {max_attempts} attempt(s) for {path}: {exc}"
                ) from exc
            sleep_before_wechat_retry(label, attempt, max_attempts, str(exc))
            continue

        if is_retryable_wechat_response(response) and attempt < max_attempts:
            sleep_before_wechat_retry(label, attempt, max_attempts, f"HTTP {response.status_code}")
            continue

        try:
            return parse_wechat_json(response, label)
        except WeChatError as exc:
            if exc.errcode in WECHAT_RETRYABLE_ERRCODES and attempt < max_attempts:
                sleep_before_wechat_retry(label, attempt, max_attempts, exc.errmsg or str(exc))
                continue
            raise

    raise WeChatError(f"{label} upload failed after {max_attempts} attempt(s) for {path}")


def upload_article_image(session: requests.Session, access_token: str, path: Path, timeout: int) -> str:
    if path.suffix.lower() not in {".jpg", ".jpeg", ".png"}:
        raise WeChatError(f"Article image must be jpg/png for uploadimg: {path}")
    if path.stat().st_size >= 1024 * 1024:
        raise WeChatError(f"Article image exceeds uploadimg 1MB limit: {path}")
    url = f"https://api.weixin.qq.com/cgi-bin/media/uploadimg?access_token={access_token}"
    data = upload_wechat_file(session, url, path, "uploadimg", timeout)
    image_url = data.get("url")
    if not image_url:
        raise WeChatError(f"uploadimg did not return url for {path}: {data}")
    return str(image_url)


def upload_cover_material(session: requests.Session, access_token: str, path: Path, timeout: int) -> str:
    url = f"https://api.weixin.qq.com/cgi-bin/material/add_material?access_token={access_token}&type=image"
    data = upload_wechat_file(session, url, path, "add_material", timeout)
    media_id = data.get("media_id")
    if not media_id:
        raise WeChatError(f"add_material did not return media_id for {path}: {data}")
    return str(media_id)


def payload_article_titles(articles: list[dict[str, Any]]) -> list[str]:
    return [normalize_space(str(item.get("title") or "")) for item in articles if item.get("title")]


def payload_article_title_keys(articles: list[dict[str, Any]]) -> list[str]:
    return [draft_title_key(title) for title in payload_article_titles(articles)]


def draft_news_items(container: dict[str, Any]) -> list[dict[str, Any]]:
    candidates: list[Any] = []
    content = container.get("content")
    if isinstance(content, dict):
        candidates.extend([content.get("news_item"), content.get("articles")])
    candidates.extend([container.get("news_item"), container.get("articles")])
    for candidate in candidates:
        if isinstance(candidate, list):
            return [item for item in candidate if isinstance(item, dict)]
    return []


def batchget_recent_drafts(session: requests.Session, access_token: str, timeout: int, limit: int = 100) -> list[dict[str, Any]]:
    drafts: list[dict[str, Any]] = []
    page_size = 20
    for offset in range(0, max(1, limit), page_size):
        response = post_wechat_json(
            session,
            f"https://api.weixin.qq.com/cgi-bin/draft/batchget?access_token={access_token}",
            {"offset": offset, "count": min(page_size, limit - offset), "no_content": 0},
            timeout,
            max_attempts=WECHAT_REQUEST_MAX_ATTEMPTS,
        )
        data = parse_wechat_json(response, "draft/batchget")
        items = data.get("item")
        if not isinstance(items, list) or not items:
            break
        drafts.extend(item for item in items if isinstance(item, dict))
        total_count = data.get("total_count")
        if isinstance(total_count, int) and offset + len(items) >= total_count:
            break
        if len(drafts) >= limit:
            break
    return drafts[:limit]


def find_recent_draft_by_titles(
    session: requests.Session,
    access_token: str,
    expected_titles: list[str],
    timeout: int,
    limit: int = 100,
) -> str:
    if not expected_titles:
        return ""
    expected_keys = [draft_title_key(title) for title in expected_titles]
    try:
        recent_items = batchget_recent_drafts(session, access_token, timeout, limit=limit)
    except WeChatError as exc:
        log(f"Could not batchget recent drafts while recovering draft/add: {exc}")
        return ""
    for item in recent_items:
        if not isinstance(item, dict):
            continue
        media_id = str(item.get("media_id") or "")
        news_items = draft_news_items(item)
        titles = [normalize_space(str(news.get("title") or "")) for news in news_items]
        title_keys = [draft_title_key(title) for title in titles]
        if media_id and title_keys == expected_keys:
            return media_id
    return ""


def recover_draft_after_ambiguous_add(
    session: requests.Session,
    access_token: str,
    articles: list[dict[str, Any]],
    timeout: int,
) -> str:
    expected_titles = payload_article_titles(articles)
    for attempt in range(1, 4):
        time.sleep(min(2.0 * attempt, 5.0))
        media_id = find_recent_draft_by_titles(session, access_token, expected_titles, timeout)
        if media_id:
            log(f"Recovered draft/add media_id from recent drafts after ambiguous response: {media_id}")
            return media_id
    return ""


def add_draft(session: requests.Session, access_token: str, articles: list[dict[str, Any]], timeout: int) -> str:
    url = f"https://api.weixin.qq.com/cgi-bin/draft/add?access_token={access_token}"
    payload = {"articles": articles}
    max_attempts = WECHAT_REQUEST_MAX_ATTEMPTS
    for attempt in range(1, max_attempts + 1):
        try:
            response = post_wechat_json(session, url, payload, timeout, max_attempts=1)
            data = parse_wechat_json(response, "draft/add")
            media_id = data.get("media_id")
            if not media_id:
                raise WeChatError(f"draft/add did not return media_id: {data}")
            return str(media_id)
        except WeChatError as exc:
            if "non-JSON response" in str(exc):
                media_id = recover_draft_after_ambiguous_add(session, access_token, articles, timeout)
                if media_id:
                    return media_id
            if is_article_size_error(exc) or attempt >= max_attempts:
                raise
            if exc.errcode not in WECHAT_RETRYABLE_ERRCODES and "request failed" not in str(exc) and "non-JSON response" not in str(exc):
                raise
            sleep_before_wechat_retry("draft/add", attempt, max_attempts, exc.errmsg or str(exc))
    raise WeChatError(f"draft/add failed after {max_attempts} attempt(s)")


def get_draft(session: requests.Session, access_token: str, media_id: str, timeout: int) -> dict[str, Any]:
    response = post_wechat_json(
        session,
        f"https://api.weixin.qq.com/cgi-bin/draft/get?access_token={access_token}",
        {"media_id": media_id},
        timeout,
        max_attempts=WECHAT_REQUEST_MAX_ATTEMPTS,
    )
    return parse_wechat_json(response, "draft/get")


def summarize_draft_get_response(data: dict[str, Any], expected_article_count: int) -> dict[str, Any]:
    news_items = data.get("news_item")
    if not isinstance(news_items, list):
        news_items = data.get("articles")
    if not isinstance(news_items, list):
        news_items = []

    titles = [
        normalize_space(str(item.get("title") or ""))
        for item in news_items
        if isinstance(item, dict)
    ]
    article_count = len(news_items)
    return {
        "ok": True,
        "article_count": article_count,
        "expected_article_count": expected_article_count,
        "matches_expected_article_count": article_count == expected_article_count,
        "titles": titles,
        "create_time": data.get("create_time"),
        "update_time": data.get("update_time"),
    }


def verify_draft_get(
    session: requests.Session,
    access_token: str,
    media_id: str,
    timeout: int,
    expected_article_count: int,
) -> dict[str, Any]:
    try:
        summary = summarize_draft_get_response(
            get_draft(session, access_token, media_id, timeout),
            expected_article_count,
        )
    except WeChatError as exc:
        summary = {
            "ok": False,
            "expected_article_count": expected_article_count,
            "errcode": exc.errcode,
            "errmsg": exc.errmsg,
            "error": str(exc),
        }
        log(f"Draft get verification failed for media_id={media_id}: {exc}")
        return summary

    log(
        "Verified draft/get: "
        f"media_id={media_id} articles={summary['article_count']}/{expected_article_count}"
    )
    return summary


def submit_publish(session: requests.Session, access_token: str, media_id: str, timeout: int) -> str:
    response = post_wechat_json(
        session,
        f"https://api.weixin.qq.com/cgi-bin/freepublish/submit?access_token={access_token}",
        {"media_id": media_id},
        timeout,
        max_attempts=WECHAT_REQUEST_MAX_ATTEMPTS,
    )
    data = parse_wechat_json(response, "freepublish/submit")
    publish_id = data.get("publish_id")
    if not publish_id:
        raise WeChatError(f"freepublish/submit did not return publish_id: {data}")
    return str(publish_id)


def fake_image_url(report_dir: Path, token: str) -> str:
    safe = quote(f"{report_dir.name}-{token}", safe="")
    return f"https://example.com/wechat-dry-run/{safe}.jpg"


def fake_static_image_url(path: str) -> str:
    safe = quote(path or "trailing-image", safe="")
    return f"https://example.com/wechat-dry-run/static/{safe}"


def translated_article_title_metadata(
    report_dir: Path,
    markdown: str | None = None,
    status: dict[str, Any] | list[Any] | None = None,
) -> dict[str, str]:
    if markdown is None:
        markdown = (report_dir / "translated.md").read_text(encoding="utf-8", errors="ignore")
    if status is None:
        status = read_json(report_dir / "translation_status.json")
    fallback_title = report_dir.name
    if isinstance(status, dict):
        fallback_title = str(status.get("title") or fallback_title)
    institution_name = infer_institution_name(report_dir.name, status, markdown[:1200])
    source_report_name = source_report_name_from_translated_dir(report_dir, status)
    title = sharpen_wechat_title(
        ensure_title_has_institution(title_from_markdown(markdown, fallback_title), institution_name),
        institution_name,
    )
    wechat_title = truncate_chars(title, WECHAT_TITLE_MAX_CHARS)
    return {
        "report_dir": str(report_dir),
        "title": title,
        "wechat_title": wechat_title,
        "institution_name": institution_name,
        "source_report_name": source_report_name,
    }


def build_article(
    report_dir: Path,
    index: int,
    args: argparse.Namespace,
    session: requests.Session | None,
    access_token: str | None,
    output_dir: Path,
    trailing_image_url: str,
) -> dict[str, Any]:
    translated_path = report_dir / "translated.md"
    markdown = translated_path.read_text(encoding="utf-8", errors="ignore")
    status = read_json(report_dir / "translation_status.json")
    title_metadata = translated_article_title_metadata(report_dir, markdown, status)
    institution_name = title_metadata["institution_name"]
    source_report_name = title_metadata["source_report_name"]
    title = title_metadata["title"]
    wechat_title = title_metadata["wechat_title"]
    figure_paths = load_figure_paths(report_dir)

    tokens = []
    for match in IMAGE_TOKEN_RE.finditer(markdown):
        token = f"[[KC_IMAGE_{match.group(1)}]]"
        if token not in tokens:
            tokens.append(token)
    tokens = tokens[: args.max_inline_images]

    image_urls: dict[str, str] = {}
    uploaded_images: list[dict[str, str]] = []
    for token in tokens:
        path = figure_paths.get(token)
        if not path:
            continue
        if args.dry_run:
            image_url = fake_image_url(report_dir, token)
            upload_path = path
        else:
            if session is None or access_token is None:
                raise RuntimeError("session and access_token are required outside dry-run")
            upload_path = prepare_article_upload_image(path, output_dir, f"article_{index:02d}_{token.strip('[]').lower()}")
            image_url = upload_article_image(session, access_token, upload_path, args.timeout)
        image_urls[token] = image_url
        uploaded_images.append({"token": token, "path": str(upload_path), "url": image_url, "source": "mineru"})

    target_min_images = min(args.min_inline_images, args.max_inline_images)
    ai_image_index = 1
    while len(uploaded_images) < target_min_images:
        ai_token = f"KC_AI_IMAGE_{ai_image_index:03d}"
        prompt = pollinations_prompt(title, ai_image_index)
        source_url = pollinations_url(prompt)
        if args.dry_run:
            image_url = fake_static_image_url(f"pollinations/{report_dir.name}/{ai_token}.jpg")
            ai_path = ""
            status_name = "dry_run"
            reason = ""
        else:
            if session is None or access_token is None:
                raise RuntimeError("session and access_token are required outside dry-run")
            ai_path_obj, source_url, status_name, reason = download_pollinations_image(
                session,
                prompt,
                output_dir / "_assets" / f"article_{index:02d}_{ai_token.lower()}.jpg",
                min(args.timeout, 45),
                title,
            )
            ai_path = str(ai_path_obj)
            image_url = upload_article_image(session, access_token, ai_path_obj, args.timeout)
        uploaded_images.append(
            {
                "token": ai_token,
                "path": ai_path,
                "url": image_url,
                "source": status_name,
                "prompt": prompt,
                "pollinations_url": source_url,
                "reason": reason,
            }
        )
        ai_image_index += 1

    cover_image = choose_cover_image(report_dir, figure_paths, output_dir / "_assets")
    if not figure_paths:
        for item in uploaded_images:
            candidate = Path(item.get("path") or "")
            if candidate.exists() and candidate.is_file():
                cover_image = candidate
                break
    if args.dry_run:
        thumb_media_id = f"DRY_RUN_THUMB_{index:02d}"
    else:
        if session is None or access_token is None:
            raise RuntimeError("session and access_token are required outside dry-run")
        thumb_media_id = upload_cover_material(session, access_token, cover_image, args.timeout)

    content, visible_text_chars, body_image_count, fitted_image_count = render_fitted_wechat_html(
        markdown,
        title,
        args.brand,
        image_urls,
        uploaded_images,
        args.body_hook,
        args.disclaimer,
        trailing_image_url,
        source_report_name,
        args.max_body_chars,
        args.max_content_chars,
        args.max_content_bytes,
    )
    if not content_within_limits(content, args.max_content_chars, args.max_content_bytes):
        raise RuntimeError(
            f"WeChat HTML for {report_dir.name} is {len(content)} chars / {utf8_byte_count(content)} bytes, "
            f"above --max-content-chars={args.max_content_chars} or --max-content-bytes={args.max_content_bytes}"
        )
    if fitted_image_count < len(uploaded_images):
        log(
            f"Compressed article {index}: kept {fitted_image_count}/{len(uploaded_images)} body images "
            f"to fit WeChat content limit."
        )

    article: dict[str, Any] = {
        "article_type": "news",
        "title": wechat_title,
        "author": truncate_utf8_bytes(args.author, WECHAT_AUTHOR_MAX_BYTES),
        "digest": "",
        "content": content,
        "thumb_media_id": thumb_media_id,
        "need_open_comment": 0,
        "only_fans_can_comment": 0,
    }
    if args.content_source_url:
        article["content_source_url"] = args.content_source_url

    return {
        "report_dir": str(report_dir),
        "translated_markdown": str(translated_path),
        "title": title,
        "wechat_title": wechat_title,
        "digest": digest_from_markdown(markdown),
        "institution_name": institution_name,
        "source_report_name": source_report_name,
        "article": article,
        "cover_image": str(cover_image),
        "inline_images": uploaded_images,
        "content_chars": len(content),
        "content_bytes": utf8_byte_count(content),
        "visible_text_chars": visible_text_chars,
        "body_image_count": body_image_count,
        "ai_image_count": sum(1 for item in uploaded_images if item.get("source") != "mineru"),
    }


def chunked(items: list[Any], size: int) -> list[list[Any]]:
    return [items[idx : idx + size] for idx in range(0, len(items), size)]


def write_json(path: Path, payload: Any) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(payload, ensure_ascii=False, indent=2), encoding="utf-8")


def is_article_size_error(exc: WeChatError) -> bool:
    return exc.errcode == 45008 or "article size out of limit" in str(exc).lower()


def article_payload(items: list[dict[str, Any]]) -> list[dict[str, Any]]:
    return [dict(item["article"]) for item in items]


def main() -> int:
    parser = argparse.ArgumentParser(description="Create WeChat Official Account drafts from KC translated reports.")
    parser.add_argument("--translated-root", default="kc_translated_reports")
    parser.add_argument("--date-folder", default="latest")
    parser.add_argument("--output-root", default="wechat_drafts")
    parser.add_argument("--max-articles", default="10")
    parser.add_argument("--article-offset", type=int, default=0)
    parser.add_argument("--articles-per-draft", type=int, default=DEFAULT_ARTICLES_PER_DRAFT)
    parser.add_argument("--max-inline-images", type=int, default=DEFAULT_MIN_INLINE_IMAGES)
    parser.add_argument("--min-inline-images", type=int, default=DEFAULT_MIN_INLINE_IMAGES)
    parser.add_argument("--max-body-chars", type=int, default=DEFAULT_BODY_VISIBLE_CHARS)
    parser.add_argument("--max-content-chars", type=int, default=DEFAULT_MAX_CONTENT_CHARS)
    parser.add_argument("--max-content-bytes", type=int, default=DEFAULT_MAX_CONTENT_BYTES)
    parser.add_argument("--brand", default=BRAND)
    parser.add_argument("--author", default=AUTHOR)
    parser.add_argument("--disclaimer", default=BOTTOM_DISCLAIMER)
    parser.add_argument("--body-hook", default=DEFAULT_BODY_HOOK)
    parser.add_argument("--trailing-image", default=DEFAULT_TRAILING_IMAGE)
    parser.add_argument("--content-source-url", default="")
    parser.add_argument("--wechat-appid", default=os.getenv("WECHAT_MP_APPID", ""))
    parser.add_argument("--wechat-secret", default=os.getenv("WECHAT_MP_APPSECRET", ""))
    parser.add_argument("--timeout", type=int, default=120)
    parser.add_argument("--publish", action="store_true", help="Submit each created draft for publishing.")
    parser.add_argument("--dry-run", action="store_true", help="Build payloads without calling WeChat APIs.")
    args = parser.parse_args()

    max_articles = parse_selection_limit(args.max_articles, "--max-articles")
    if args.article_offset < 0:
        raise ValueError("--article-offset must be non-negative")
    if not 1 <= args.articles_per_draft <= 9:
        raise ValueError("--articles-per-draft must be between 1 and 9")
    if args.max_inline_images < 0:
        raise ValueError("--max-inline-images must be non-negative")
    if args.min_inline_images < 0:
        raise ValueError("--min-inline-images must be non-negative")
    if args.max_body_chars < 200:
        raise ValueError("--max-body-chars must be at least 200")
    if not args.dry_run and (not args.wechat_appid or not args.wechat_secret):
        raise ValueError("WECHAT_MP_APPID and WECHAT_MP_APPSECRET are required unless --dry-run is set")

    root = Path(args.translated_root)
    date_dir = latest_date_dir(root) if args.date_folder == "latest" else root / args.date_folder
    if not date_dir.exists():
        raise RuntimeError(f"Date folder not found: {date_dir}")

    report_dirs = find_report_dirs(date_dir)
    if max_articles is None:
        selected = report_dirs[args.article_offset :]
    else:
        selected = report_dirs[args.article_offset : args.article_offset + max_articles]
    if not selected:
        raise RuntimeError(f"No translated reports selected from {date_dir}")

    output_dir = Path(args.output_root) / date_dir.name
    output_dir.mkdir(parents=True, exist_ok=True)
    input_selected_count = len(selected)
    skipped_title_policy: list[dict[str, str]] = []
    allowed_selected: list[Path] = []
    for report_dir in selected:
        metadata = translated_article_title_metadata(report_dir)
        reason = wechat_title_policy_skip_reason(metadata["wechat_title"])
        if reason:
            record = dict(metadata)
            record["skip_reason"] = reason
            skipped_title_policy.append(record)
            log(
                "Skipped WeChat draft article by title policy: "
                f"{metadata['wechat_title']} ({reason})"
            )
        else:
            allowed_selected.append(report_dir)
    selected = allowed_selected

    if not selected:
        summary_path = output_dir / "wechat_draft_summary.json"
        summary = {
            "date_folder": date_dir.name,
            "dry_run": args.dry_run,
            "publish": args.publish,
            "max_articles": "all" if max_articles is None else max_articles,
            "input_selected_count": input_selected_count,
            "selected_count": 0,
            "skipped_title_policy_count": len(skipped_title_policy),
            "skipped_title_policy": skipped_title_policy,
            "draft_count": 0,
            "status": "skipped_title_policy",
            "message": f"All selected translated reports were blocked by WeChat title policy from {date_dir}",
            "drafts": [],
            "articles": [],
        }
        write_json(summary_path, summary)
        log(f"All selected translated reports blocked by title policy; wrote skip summary: {summary_path}")
        return 0

    log(
        f"Selected {len(selected)} translated reports from {date_dir} "
        f"(skipped_title_policy={len(skipped_title_policy)}/{input_selected_count})"
    )

    session: requests.Session | None = None
    access_token: str | None = None
    if not args.dry_run:
        session = requests.Session()
        access_token = get_stable_access_token(session, args.wechat_appid, args.wechat_secret, args.timeout)
        log("Fetched WeChat access token")

    trailing_image_url = ""
    trailing_image_path = resolve_repo_asset_path(args.trailing_image)
    if args.trailing_image and not trailing_image_path:
        raise RuntimeError(f"Trailing image not found: {args.trailing_image}")
    if trailing_image_path:
        if args.dry_run:
            trailing_image_url = fake_static_image_url(str(trailing_image_path))
        else:
            if session is None or access_token is None:
                raise RuntimeError("session and access_token are required outside dry-run")
            trailing_image_url = upload_article_image(session, access_token, trailing_image_path, args.timeout)
            log(f"Uploaded trailing image: {trailing_image_path}")

    built_articles = [
        build_article(report_dir, idx, args, session, access_token, output_dir, trailing_image_url)
        for idx, report_dir in enumerate(selected, 1)
    ]

    drafts = []

    def create_draft(group: list[dict[str, Any]]) -> None:
        articles = article_payload(group)
        payload_bytes = utf8_byte_count(json.dumps({"articles": articles}, ensure_ascii=False, separators=(",", ":")))
        if args.dry_run:
            media_id = f"DRY_RUN_DRAFT_{len(drafts) + 1:02d}"
            publish_id = f"DRY_RUN_PUBLISH_{len(drafts) + 1:02d}" if args.publish else ""
            reused_existing = False
            draft_get = {
                "ok": True,
                "dry_run": True,
                "article_count": len(articles),
                "expected_article_count": len(articles),
                "matches_expected_article_count": True,
                "titles": [item.get("title", "") for item in articles],
            }
        else:
            if session is None or access_token is None:
                raise RuntimeError("session and access_token are required outside dry-run")
            existing_media_id = find_recent_draft_by_titles(
                session,
                access_token,
                payload_article_titles(articles),
                args.timeout,
            )
            if existing_media_id:
                media_id = existing_media_id
                reused_existing = True
                log(f"Reusing existing WeChat draft with the same article titles: media_id={media_id}")
            else:
                reused_existing = False
                try:
                    media_id = add_draft(session, access_token, articles, args.timeout)
                except WeChatError as exc:
                    if is_article_size_error(exc) and len(group) > 1:
                        split_at = max(1, len(group) // 2)
                        log(
                            "WeChat rejected draft group as too large; "
                            f"splitting {len(group)} articles into {split_at}+{len(group) - split_at} and retrying."
                        )
                        create_draft(group[:split_at])
                        create_draft(group[split_at:])
                        return
                    raise
            draft_get = verify_draft_get(session, access_token, media_id, args.timeout, len(articles))
            publish_id = submit_publish(session, access_token, media_id, args.timeout) if args.publish else ""

        draft_index = len(drafts) + 1
        payload_path = output_dir / f"draft_payload_{draft_index:02d}.json"
        write_json(payload_path, {"articles": articles})
        drafts.append(
            {
                "draft_index": draft_index,
                "media_id": media_id,
                "publish_id": publish_id,
                "published": bool(publish_id),
                "reused_existing": reused_existing,
                "article_count": len(articles),
                "payload_bytes": payload_bytes,
                "payload": str(payload_path),
                "titles": [item["title"] for item in group],
                "wechat_titles": [item["wechat_title"] for item in group],
                "draft_get": draft_get,
            }
        )
        if publish_id:
            log(f"Draft {draft_index}: articles={len(articles)} media_id={media_id} publish_id={publish_id}")
        else:
            log(f"Draft {draft_index}: articles={len(articles)} media_id={media_id}")

    for group in chunked(built_articles, args.articles_per_draft):
        create_draft(group)

