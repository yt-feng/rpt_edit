def strip_markdown_markup(text: str) -> str:
    text = re.sub(r"^\s*#{1,6}\s*", "", text)
    text = re.sub(r"\*\*([^*]+)\*\*", r"\1", text)
    text = re.sub(r"`([^`]+)`", r"\1", text)
    text = MD_IMAGE_RE.sub("", text)
    text = IMAGE_TOKEN_RE.sub("", text)
    return normalize_space(text)


def title_from_markdown(markdown: str, fallback: str) -> str:
    headings: list[str] = []
    for raw in markdown.splitlines():
        line = raw.strip()
        if line.startswith("#"):
            title = strip_markdown_markup(line)
            if title and not APPENDIX_RE.match(line):
                headings.append(title)
        if len(headings) >= 2:
            break
    if not headings:
        return truncate_chars(fallback, RAW_MARKDOWN_TITLE_MAX_CHARS)
    if len(headings) == 1:
        return truncate_chars(headings[0], RAW_MARKDOWN_TITLE_MAX_CHARS)
    combined = f"{headings[0]}：{headings[1]}"
    return truncate_chars(combined, RAW_MARKDOWN_TITLE_MAX_CHARS)


def digest_from_markdown(markdown: str) -> str:
    for raw in markdown.splitlines():
        line = strip_markdown_markup(raw)
        if len(line) >= 40 and not TRAILING_DISCLOSURE_RE.search(line):
            return truncate_utf8_bytes(line, WECHAT_DIGEST_MAX_BYTES)
    return ""


def clean_markdown(markdown: str) -> str:
    cleaned: list[str] = []
    in_code = False
    for raw in markdown.splitlines():
        line = raw.rstrip()
        if line.strip().startswith("```"):
            in_code = not in_code
            continue
        if in_code:
            continue
        if APPENDIX_RE.match(line):
            break
        if USER_NOISE_LINE_RE.match(normalize_space(line)):
            continue
        if TRAILING_DISCLOSURE_RE.search(line):
            break
        cleaned.append(line)
    text, _stock_changes = sanitize_wechat_stock_language("\n".join(cleaned).strip())
    return text


