def compose_limited_html(parts: list[str], tail_parts: list[str], max_chars: int) -> str:
    tail = [part for part in tail_parts if part]
    if max_chars <= 0:
        return "\n".join(part for part in [*parts, *tail] if part)
    full = "\n".join(part for part in [*parts, *tail] if part)
    if len(full) <= max_chars:
        return full

    limited: list[str] = []
    for part in parts:
        candidate = "\n".join(item for item in [*limited, part, *tail] if item)
        if len(candidate) > max_chars:
            break
        limited.append(part)
    return "\n".join(part for part in [*limited, *tail] if part)


def content_within_limits(content: str, max_chars: int, max_bytes: int) -> bool:
    if max_chars > 0 and len(content) > max_chars:
        return False
    if max_bytes > 0 and utf8_byte_count(content) > max_bytes:
        return False
    return True


def render_fitted_wechat_html(
    markdown: str,
    title: str,
    brand: str,
    image_urls: dict[str, str],
    uploaded_images: list[dict[str, str]],
    hook_text: str,
    disclaimer: str,
    trailing_image_url: str,
    source_report_name: str,
    max_visible_chars: int,
    max_content_chars: int,
    max_content_bytes: int,
) -> tuple[str, int, int, int]:
    image_limits = [len(uploaded_images)]
    for value in [2, 1, 0]:
        value = min(value, len(uploaded_images))
        if value not in image_limits:
            image_limits.append(value)
    visible_budgets = [
        max_visible_chars,
        min(max_visible_chars, 1600),
        min(max_visible_chars, 1200),
        min(max_visible_chars, 900),
        min(max_visible_chars, 650),
        min(max_visible_chars, 450),
        min(max_visible_chars, 300),
    ]
    visible_budgets = [value for idx, value in enumerate(visible_budgets) if value >= 200 and value not in visible_budgets[:idx]]

    last_content = ""
    last_visible = 0
    last_body_images = 0
    for image_limit in image_limits:
        body_images = [
            {"url": item["url"], "alt": item.get("token") or "chart"}
            for item in uploaded_images[:image_limit]
            if item.get("url")
        ]
        for visible_budget in visible_budgets:
            content, visible_text_chars, body_image_count = markdown_to_wechat_html(
                markdown,
                title,
                brand,
                image_urls,
                body_images,
                hook_text,
                disclaimer,
                trailing_image_url,
                source_report_name,
                visible_budget,
                max_content_chars,
            )
            last_content = content
            last_visible = visible_text_chars
            last_body_images = body_image_count
            if content_within_limits(content, max_content_chars, max_content_bytes):
                return content, visible_text_chars, body_image_count, image_limit

    raise RuntimeError(
        "WeChat HTML still exceeds limits after compression: "
        f"chars={len(last_content)}, bytes={utf8_byte_count(last_content)}, "
        f"visible={last_visible}, body_images={last_body_images}, "
        f"max_chars={max_content_chars}, max_bytes={max_content_bytes}"
    )


def markdown_to_wechat_html(
    markdown: str,
    title: str,
    brand: str,
    image_urls: dict[str, str],
    body_images: list[dict[str, str]],
    hook_text: str,
    disclaimer: str,
    trailing_image_url: str,
    source_report_name: str,
    max_visible_chars: int,
    max_chars: int,
) -> tuple[str, int, int]:
    parts: list[str] = [brand_header_html(brand, title)]
    paragraph: list[str] = []
    list_items: list[str] = []
    rendered_image_urls: set[str] = set()
    selected_image_urls = [item["url"] for item in body_images if item.get("url")]
    selected_image_set = set(selected_image_urls)
    body_budget = max(0, max_visible_chars - visible_char_count(hook_text))
    text_used = 0

    def remaining_chars() -> int:
        return max(0, body_budget - text_used)

    def fit_text(text: str) -> str:
        nonlocal text_used
        if body_budget <= 0 or text_used >= body_budget:
            return ""
        count = visible_char_count(text)
        if count <= remaining_chars():
            text_used += count
            return text
        if remaining_chars() < 24:
            text_used = body_budget
            return ""
        fitted = truncate_visible_text(text, remaining_chars())
        text_used = body_budget
        return fitted

    def maybe_render_image(url: str, alt: str) -> None:
        if not url or url not in selected_image_set or url in rendered_image_urls:
            return
        parts.append(image_html(url, alt=alt))
        rendered_image_urls.add(url)

    def flush_paragraph() -> None:
        nonlocal paragraph
        if paragraph:
            fitted = fit_text(" ".join(paragraph))
            rendered = paragraph_html(fitted)
            if rendered:
                parts.append(rendered)
            paragraph = []

    def flush_list() -> None:
        nonlocal list_items
        if list_items:
            rendered_items = []
            for item in list_items:
                fitted = fit_text(item)
                if fitted:
                    rendered_items.append(fitted)
                if text_used >= body_budget:
                    break
            if rendered_items:
                body = "".join(f"<li>{inline_markdown(item, context='list')}</li>" for item in rendered_items)
                parts.append(f'<ul style="margin:10px 0 12px;padding-left:22px;line-height:1.7;color:#202631;font-size:16px;">{body}</ul>')
            list_items = []

    for raw in clean_markdown(markdown).splitlines():
        line = raw.strip()
        if not line:
            flush_paragraph()
            flush_list()
            continue

        if line.startswith(">"):
            flush_paragraph()
            flush_list()
            quote = normalize_space(re.sub(r"^>\s?", "", line))
            fitted = fit_text(quote)
            if fitted:
                parts.append(kc_comment_html(fitted))
            continue

        token_match = IMAGE_TOKEN_RE.fullmatch(line)
        md_image_match = MD_IMAGE_RE.fullmatch(line)
        if token_match:
            flush_paragraph()
            flush_list()
            token = f"[[KC_IMAGE_{token_match.group(1)}]]"
            url = image_urls.get(token)
            maybe_render_image(url or "", token)
            continue
        if md_image_match:
            flush_paragraph()
            flush_list()
            ref = md_image_match.group(2).strip()
            url = image_urls.get(ref) or ref
            if url.startswith("http://") or url.startswith("https://"):
                maybe_render_image(url, md_image_match.group(1))
            continue

        if is_figure_meta_line(line):
            flush_paragraph()
            flush_list()
            continue

        heading = re.match(r"^(#{1,6})\s+(.+)$", line)
        if heading:
            flush_paragraph()
            flush_list()
            fitted = fit_text(heading.group(2))
            if fitted:
                parts.append(heading_html(len(heading.group(1)), fitted))
            continue

        bullet = re.match(r"^[-*]\s+(.+)$", line)
        if bullet:
            flush_paragraph()
            list_items.append(bullet.group(1))
            continue

        paragraph.append(line)

    flush_paragraph()
    flush_list()
    supplemental_images = [
        image_html(item["url"], alt=item.get("alt") or "KC Desk")
        for item in body_images
        if item.get("url") and item["url"] not in rendered_image_urls
    ]
    tail = [*supplemental_images, hook_html(hook_text), footer_html(disclaimer)]
    if trailing_image_url:
        tail.append(image_html(trailing_image_url, alt="KC Desk"))
    if source_report_name:
        tail.append(source_report_footer_html(source_report_name))
    content = compose_limited_html(parts, tail, max_chars)
    total_visible = text_used + visible_char_count(hook_text)
    return content, total_visible, len(body_images)


def resolve_asset_path(report_dir: Path, raw_path: str) -> Path | None:
    raw = (raw_path or "").strip()
    if not raw:
        return None
    path = Path(raw)
    candidates = []
    if path.is_absolute():
        candidates.append(path)
    else:
        candidates.extend(
            [
                report_dir / raw,
                report_dir / "assets" / raw,
                Path.cwd() / raw,
            ]
        )
    for candidate in candidates:
        if candidate.exists() and candidate.is_file():
            return candidate
    return None


def resolve_repo_asset_path(raw_path: str) -> Path | None:
    raw = (raw_path or "").strip()
    if not raw:
        return None
    if raw.startswith("https://github.com/") and "/blob/" in raw:
        raw = raw.split("/blob/", 1)[1].split("/", 1)[1]
    path = Path(raw)
    candidates = [path] if path.is_absolute() else [Path.cwd() / path, path]
    for candidate in candidates:
        if candidate.exists() and candidate.is_file():
            return candidate
    return None


def load_figure_paths(report_dir: Path) -> dict[str, Path]:
    manifest = read_json(report_dir / "figure_manifest.json")
    figures: dict[str, Path] = {}
    if not isinstance(manifest, list):
        return figures
    for item in manifest:
        if not isinstance(item, dict):
            continue
        token = str(item.get("token") or "")
        if not token:
            continue
        for key in ["relative_path", "path", "source_path"]:
            resolved = resolve_asset_path(report_dir, str(item.get(key) or ""))
            if resolved:
                figures[token] = resolved
                break
    return figures


def png_chunk(kind: bytes, data: bytes) -> bytes:
    import binascii

    checksum = binascii.crc32(kind + data) & 0xFFFFFFFF
    return struct.pack(">I", len(data)) + kind + data + struct.pack(">I", checksum)


def write_fallback_cover(path: Path, width: int = 1200, height: int = 675) -> None:
    bg = (247, 243, 232)
    ink = (20, 32, 51)
    gold = (201, 162, 39)
    rows = []
    for y in range(height):
        row = bytearray()
        for x in range(width):
            if x < 34 or 92 <= y < 114:
                color = gold
            elif y < 92:
                color = ink
            else:
                color = bg
            row.extend(color)
        rows.append(b"\x00" + bytes(row))
    raw = b"".join(rows)
    ihdr = struct.pack(">IIBBBBB", width, height, 8, 2, 0, 0, 0)
    path.write_bytes(
        b"\x89PNG\r\n\x1a\n"
        + png_chunk(b"IHDR", ihdr)
        + png_chunk(b"IDAT", zlib.compress(raw, level=9))
        + png_chunk(b"IEND", b"")
    )


def choose_cover_image(report_dir: Path, figure_paths: dict[str, Path], fallback_dir: Path) -> Path:
    for token in sorted(figure_paths):
        path = figure_paths[token]
        if path.exists() and path.suffix.lower() in {".jpg", ".jpeg", ".png", ".gif", ".bmp"}:
            return path
    fallback_dir.mkdir(parents=True, exist_ok=True)
    fallback = fallback_dir / "fallback_cover.png"
    if not fallback.exists():
        write_fallback_cover(fallback)
    return fallback


