    working = image.convert("RGB")
    working.thumbnail((1280, 1280), Image.Resampling.LANCZOS)
    quality = 88
    while True:
        working.save(path, format="JPEG", quality=quality, optimize=True, progressive=True)
        if path.stat().st_size < max_bytes:
            return path
        if quality > 58:
            quality -= 8
