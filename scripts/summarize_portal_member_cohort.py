#!/usr/bin/env python3
"""Aggregate a current-access cohort without exporting account identities.

The input snapshot is generated by the production access evaluator. Analytics
identities are used only in memory; anonymous events are linked only inside an
unambiguous explicit client session, never by IP or device identity.
"""

from __future__ import annotations

import json
from collections import Counter, defaultdict
from datetime import datetime, timedelta
from pathlib import Path
from typing import Any, Iterable
from urllib.parse import quote

import summarize_portal_growth_range as growth


SCHEMA = "portal-current-access-cohort-v1"
SNAPSHOT_SCHEMA = "portal-growth-current-users-v1"
COHORTS = ("current_unrestricted_access", "current_limited_or_scoped_access", "without_current_access")
SUCCESS = {"success", "ok", "completed"}


def placeholder_email(value: str) -> bool:
    return not value or value.split("@", 1)[0] == "redacted" or value.endswith(".invalid")


def snapshot_accounts(snapshot: dict[str, Any]) -> tuple[list[dict[str, Any]], dict[str, int], dict[str, int]]:
    if (not isinstance(snapshot, dict) or snapshot.get("schema") != SNAPSHOT_SCHEMA
            or snapshot.get("complete") is not True or not growth.parse_instant(snapshot.get("generated_at"))
            or not isinstance(snapshot.get("users"), list)
            or snapshot.get("user_count") != len(snapshot["users"])):
        raise ValueError("A complete canonical current-user snapshot is required")
    accounts, by_id, by_email = [], {}, {}
    for raw in snapshot["users"]:
        if not isinstance(raw, dict):
            raise ValueError("Invalid canonical current-user snapshot")
        identity = growth.clean_text(raw.get("id"), 160)
        email = growth.clean_text(raw.get("email"), 240).lower()
        access = raw.get("effective_access")
        if (not identity or identity in by_id
                or raw.get("role") not in {"user", "super", "operator"}
                or not isinstance(raw.get("disabled"), bool) or not isinstance(access, dict)
                or not isinstance(access.get("active"), bool) or access.get("source") == "error"):
            raise ValueError("Invalid or ambiguous canonical current-user snapshot")
        limit = access.get("download_limit")
        if not isinstance(limit, int) or isinstance(limit, bool) or limit < 0:
            raise ValueError("Canonical access quota is unavailable")
        current = bool(not raw["disabled"] and raw["role"] == "user" and access["active"])
        # The canonical evaluator can merge an unlimited annual/admin grant
        # with a trial component. Its chosen zero-limit access remains full
        # access; only a standalone trial source is excluded here.
        unrestricted = bool(current and access.get("access_mode") == "all" and limit == 0
                            and access.get("source") != "vid2ppt_trial")
        cohort = COHORTS[0] if unrestricted else COHORTS[1] if current else COHORTS[2]
        index = len(accounts)
        accounts.append({**raw, "cohort": cohort})
        by_id[identity] = index
        # The canonical UI projection intentionally redacts some addresses to
        # a shared placeholder. Keep exact-ID accounts, but never email-join
        # a duplicate/placeholder address.
        by_email[email] = -1 if placeholder_email(email) or email in by_email else index
    return accounts, by_id, by_email


def matched_account(event: dict[str, Any], by_id: dict[str, int], by_email: dict[str, int], accounts: list[dict[str, Any]]) -> tuple[str, int | None]:
    user = event.get("user")
    if user is None:
        return "anonymous", None
    if not isinstance(user, dict):
        return "unknown_authenticated", None
    if user.get("role") in {"super", "operator", "admin"}:
        return "privileged", None
    identity = growth.clean_text(user.get("id"), 160)
    email = growth.clean_text(user.get("email"), 240).lower()
    if identity:
        if identity not in by_id:
            return "unknown_authenticated", None
        index = by_id[identity]
        canonical_email = growth.clean_text(accounts[index].get("email"), 240).lower()
        email_index = by_email.get(email, -1)
        if email and (email_index >= 0 and email_index != index
                      or not placeholder_email(canonical_email) and email != canonical_email):
            return "unknown_authenticated", None
        return "matched", index
    if email:
        index = by_email.get(email, -1)
        if index >= 0:
            return "matched", index
    return "unknown_authenticated", None


def public_catalog(catalog: dict[str, Any] | list[Any]) -> dict[str, dict[str, str]]:
    items = catalog.get("items", []) if isinstance(catalog, dict) else catalog
    result = {}
    for item in items if isinstance(items, list) else []:
        if not isinstance(item, dict):
            continue
        identity = growth.clean_text(item.get("id"), 160)
        if identity:
            result[identity] = {
                "report_id": identity,
                "title": growth.clean_text(item.get("title_zh") or item.get("title") or item.get("name"), 360),
                "path": "/reports/" + quote(identity, safe="") + ".html",
            }
    return result


def known_public_path(value: Any, report_paths: set[str]) -> str:
    if not growth.clean_text(value):
        return "unknown"
    path = growth.normalize_path(value)
    fixed = {"/", "/index.html", "/report.html", "/reports/", "/reports", "/reports/topics.html",
             "/newsfeed.html", "/newsfeed", "/charts", "/charts.html", "/courses", "/courses.html",
             "/blog/", "/blog", "/account.html", "/membership.html", "/about.html"}
    if path in fixed or path in report_paths:
        return path
    if path.startswith("/blog/"):
        return "/blog/"
    # Do not export arbitrary client paths, which may contain account details.
    return "other_public_page"


def client_time(event: dict[str, Any], start: datetime, end: datetime) -> datetime | None:
    value = growth.parse_instant(event.get("client_ts"))
    return value if value and start <= value < end else None


def ordered_pair(rows: list[dict[str, Any]], first: str, second: str, start: datetime, end: datetime) -> bool:
    left = [client_time(row, start, end) for row in rows if row.get("type") == first]
    right = [client_time(row, start, end) for row in rows if row.get("type") == second]
    return any(a < b for a in left if a for b in right if b)


def session_object(key: str, rows: list[dict[str, Any]], start: Any) -> growth.Session:
    first = rows[0]
    return growth.Session(key=key, visitor="", date=start,
                          landing_path=growth.normalize_path(first.get("landing_path") or first.get("path")),
                          referrer_host=growth.clean_text(first.get("referrer_host")) or growth.normalize_host(first.get("referrer")),
                          utm_source=growth.clean_text(first.get("utm_source")),
                          utm_medium=growth.clean_text(first.get("utm_medium")), events=rows)


def build_member_cohort(events: Iterable[dict[str, Any]], snapshot: dict[str, Any], start_date: str, end_date: str,
                        *, catalog: dict[str, Any] | list[Any] = (), site_host: str = "", min_count: int = 2) -> dict[str, Any]:
    start, end = growth.parse_date(start_date), growth.parse_date(end_date)
    if not start or not end or end < start or min_count < 1:
        raise ValueError("Invalid cohort analysis window")
    begin = datetime.combine(start, datetime.min.time(), growth.BJT)
    stop = datetime.combine(end + timedelta(days=1), datetime.min.time(), growth.BJT)
    accounts, by_id, by_email = snapshot_accounts(snapshot)
    reports = public_catalog(catalog)
    report_paths = {row["path"] for row in reports.values()}
    hosts = {growth.normalize_host(site_host)} - {""}
    rows, duplicates = growth.deduplicate_events(events)
    coverage: Counter[str] = Counter(duplicate_events_removed=duplicates)
    sessions: dict[str, list[dict[str, Any]]] = defaultdict(list)
    server_events = []
    for row in rows:
        day = growth.event_date(row)
        if not day or not start <= day <= end:
            coverage["outside_window_events"] += 1
            continue
        if row.get("type") == "form_confirmation":
            server_events.append(row)
        if not growth.is_product_event(row):
            coverage["bot_admin_or_server_events_excluded"] += 1
            continue
        key = growth.clean_text(row.get("session_id"), 160)
        if not key:
            coverage["events_without_explicit_session"] += 1
            continue
        sessions[key].append(row)
    linked: dict[int, list[growth.Session]] = defaultdict(list)
    authenticated_active: set[int] = set()
    authenticated_product_active: set[int] = set()
    for key, session_rows in sessions.items():
        identities, states = set(), set()
        for row in session_rows:
            state, identity = matched_account(row, by_id, by_email, accounts)
            states.add(state)
            if identity is not None:
                identities.add(identity)
        if "privileged" in states or any(accounts[index]["role"] != "user" for index in identities):
            coverage["privileged_sessions_excluded"] += 1
        elif len(identities) > 1:
            coverage["multi_account_sessions_excluded"] += 1
        elif "unknown_authenticated" in states:
            coverage["unknown_authenticated_sessions_excluded"] += 1
        elif not identities:
            coverage["anonymous_only_sessions"] += 1
        else:
            index = next(iter(identities))
            linked[index].append(session_object(key, session_rows, start))
            coverage["unambiguous_account_sessions"] += 1
            coverage["anonymous_events_linked_in_same_session"] += sum(row.get("user") is None for row in session_rows)
            authenticated = [row for row in session_rows if matched_account(row, by_id, by_email, accounts)[1] == index]
            if session_object(key, authenticated, start).is_intentionally_engaged():
                authenticated_active.add(index)
            product_rows = [row for row in authenticated if row.get("type") != "account_auth"]
            if product_rows and session_object(key, product_rows, start).is_intentionally_engaged():
                authenticated_product_active.add(index)
    coverage["explicit_sessions_examined"] = len(sessions)
    for key in ("outside_window_events", "bot_admin_or_server_events_excluded", "events_without_explicit_session",
                "privileged_sessions_excluded", "multi_account_sessions_excluded", "unknown_authenticated_sessions_excluded",
                "anonymous_only_sessions", "unambiguous_account_sessions", "anonymous_events_linked_in_same_session"):
        coverage.setdefault(key, 0)

    def summarize(indices: set[int]) -> dict[str, Any]:
        observed = indices.intersection(linked)
        selected = [session for index in observed for session in linked[index]]
        selected_events = [row for session in selected for row in session.events]
        channels: Counter[str] = Counter()
        landing_accounts: dict[str, set[int]] = defaultdict(set)
        first_report_accounts: dict[str, set[int]] = defaultdict(set)
        report_activity: dict[str, dict[str, set[Any]]] = defaultdict(lambda: defaultdict(set))
        attribution_coverage: Counter[str] = Counter()
        report_coverage: Counter[str] = Counter()
        for index in observed:
            candidates = []
            for session in linked[index]:
                times = {growth.parse_instant(row.get("session_started_at")) for row in session.events}
                times.discard(None)
                if len(times) != 1:
                    attribution_coverage["sessions_without_consistent_start"] += 1
                    continue
                instant = next(iter(times))
                if not begin <= instant < stop:
                    attribution_coverage["sessions_started_outside_window"] += 1
                    continue
                candidates.append((instant, session))
            candidates.sort(key=lambda pair: pair[0])
            if not candidates or len(candidates) > 1 and candidates[0][0] == candidates[1][0]:
                channels["unknown"] += 1
                attribution_coverage["accounts_without_unambiguous_window_entry"] += 1
                continue
            entry = candidates[0][1]
            channel = growth.channel_for_session(entry, hosts)
            channels["direct_or_unknown" if channel == "direct" else channel] += 1
            landing = known_public_path(entry.events[0].get("landing_path"), report_paths)
            landing_accounts[landing].add(index)
            possible_reports = {str(row.get("report_id")) for row in entry.events
                                if row.get("type") == "page_view" and growth.normalize_path(row.get("path")) == entry.landing_path
                                and str(row.get("report_id")) in reports}
            if len(possible_reports) == 1:
                first_report_accounts[next(iter(possible_reports))].add(index)
            else:
                attribution_coverage["accounts_without_catalog_report_entry"] += 1
        for index in observed:
            for session in linked[index]:
                register_times = [client_time(row, begin, stop) for row in session.events
                                  if row.get("type") == "account_auth" and row.get("action") == "register"
                                  and row.get("status") in SUCCESS]
                grouped: dict[str, list[dict[str, Any]]] = defaultdict(list)
                for row in session.events:
                    identity = str(row.get("report_id") or "")
                    if row.get("type") in {"report_open", "download_attempt", "download_success"} and not growth.is_report_loading_event(row):
                        report_coverage["catalog_matched_events" if identity in reports else "unmatched_or_missing_report_events"] += 1
                    if identity in reports and row.get("type") in {"report_open", "download_attempt", "download_success"} and not growth.is_report_loading_event(row):
                        grouped[identity].append(row)
                for identity, report_rows in grouped.items():
                    counts = report_activity[identity]
                    counts["accounts"].add(index)
                    for event_type in ("report_open", "download_attempt", "download_success"):
                        if any(row.get("type") == event_type for row in report_rows):
                            counts[event_type + "_sessions"].add(session.key)
                    attempts = [row for row in report_rows if row.get("type") == "download_attempt"]
                    successes = [row for row in report_rows if row.get("type") == "download_success"]
                    if attempts and successes:
                        usable = any(client_time(row, begin, stop) for row in attempts) and any(client_time(row, begin, stop) for row in successes)
                        counts["download_pairs_with_usable_client_time_sessions" if usable else "download_pairs_without_usable_client_time_sessions"].add(session.key)
                    if ordered_pair(report_rows, "download_attempt", "download_success", begin, stop):
                        counts["ordered_attempt_then_success_sessions"].add(session.key)
                    if any(t < registered for row in report_rows if row.get("type") == "report_open"
                           for t in [client_time(row, begin, stop)] if t for registered in register_times if registered):
                        counts["report_open_before_registration_sessions"].add(session.key)
        visible_reports = []
        for identity, counts in sorted(report_activity.items(), key=lambda pair: (-len(pair[1]["accounts"]), pair[0])):
            if len(counts["accounts"]) < min_count:
                continue
            item = {**reports[identity], **{key: len(counts[key]) for key in (
                "accounts", "report_open_sessions", "download_attempt_sessions", "download_success_sessions",
                "ordered_attempt_then_success_sessions", "report_open_before_registration_sessions",
                "download_pairs_with_usable_client_time_sessions", "download_pairs_without_usable_client_time_sessions")}}
            if item["download_pairs_without_usable_client_time_sessions"] and not item["download_pairs_with_usable_client_time_sessions"]:
                item["ordered_attempt_then_success_sessions"] = None
            visible_reports.append(item)
        metrics = growth.session_metrics(selected, hosts)
        # The legacy visitor field counts browser identities. This cohort uses
        # verified accounts, already counted above, and must not invent a UV.
        metrics.pop("visitors", None)
        for key in ("sessions_without_consistent_start", "sessions_started_outside_window",
                    "accounts_without_unambiguous_window_entry", "accounts_without_catalog_report_entry"):
            attribution_coverage.setdefault(key, 0)
        return {
            "current_accounts": len(indices), "observed_accounts": len(observed),
            "accounts_without_linkable_window_events": len(indices - observed),
            "authenticated_intentional_active_accounts": len(indices.intersection(authenticated_active)),
            "authenticated_product_active_accounts": len(indices.intersection(authenticated_product_active)),
            "intentional_engaged_accounts_in_linked_sessions": sum(any(s.is_intentionally_engaged() for s in linked[index]) for index in observed),
            "snapshot_registrations_in_window": sum(bool((created := growth.parse_instant(accounts[index].get("created_at"))) and begin <= created < stop) for index in indices),
            "session_metrics": metrics,
            "earliest_observed_window_entry": {
                "channels": [{"channel": key, "accounts": value} for key, value in channels.most_common()],
                "landing_pages": [{"path": path, "accounts": len(values)} for path, values in sorted(landing_accounts.items(), key=lambda pair: (-len(pair[1]), pair[0])) if len(values) >= min_count][:30],
                "catalog_report_pages": [{**reports[identity], "accounts": len(values)} for identity, values in sorted(first_report_accounts.items(), key=lambda pair: (-len(pair[1]), pair[0])) if len(values) >= min_count][:30],
                "coverage": dict(attribution_coverage),
                "suppressed_landing_groups": sum(len(values) < min_count for values in landing_accounts.values()),
                "suppressed_report_groups": sum(len(values) < min_count for values in first_report_accounts.values()),
            },
            "report_activity": visible_reports[:30],
            "report_event_coverage": {key: report_coverage[key] for key in ("catalog_matched_events", "unmatched_or_missing_report_events")},
            "report_activity_groups_suppressed": sum(len(counts["accounts"]) < min_count for counts in report_activity.values()),
            "membership_request_diagnostics": growth.public_membership_diagnostics(selected),
            "download_diagnostics": growth.public_download_diagnostics(selected),
            "post_download_diagnostics": growth.public_post_download_diagnostics(selected_events, start, end),
            "journey_diagnostics": growth.public_journey_diagnostics(selected_events, start, end),
        }

    normal = {index for index, account in enumerate(accounts) if account["role"] == "user"}
    return {
        "schema": SCHEMA, "start_date": start_date, "end_date": end_date,
        "generated_at": datetime.now(growth.BJT).isoformat(timespec="seconds"),
        "snapshot_generated_at": snapshot["generated_at"], "snapshot_complete": True,
        "snapshot_counts": {"accounts": len(accounts), "normal_accounts": len(normal),
                            "privileged_accounts_excluded": len(accounts) - len(normal),
                            "disabled_normal_accounts": sum(accounts[index]["disabled"] for index in normal)},
        "join_coverage": dict(coverage),
        "cohorts": {name: summarize({index for index in normal if accounts[index]["cohort"] == name}) for name in COHORTS},
        "unattributed_server_form_confirmations": growth.public_journey_diagnostics(server_events, start, end)["form_confirmation_results"],
        "minimum_accounts_per_public_page_group": min_count,
        "notes": [
            "Current unrestricted access means a normal enabled account with canonical active all-report access, zero download limit, and no standalone trial source; it does not mean paid membership.",
            "Limited, scoped and trial access is reported separately. Current permissions do not reconstruct membership at historical event time.",
            "Anonymous events are linked only within an explicit session containing exactly one authenticated account matched to the complete current snapshot. Multi-account, privileged and unknown-authenticated sessions are excluded.",
            "Earliest observed entry is confined to this window; it is not lifetime acquisition or proof that a page caused conversion. Missing referrers remain direct_or_unknown.",
            "Account activity and registrations are observations; no purchase or revenue attribution is available. Snapshot registration dates and observed client registration successes are separate.",
            "Authenticated product-active accounts require an intentional authenticated product action; login/registration alone does not qualify. The broader intentional-active count includes successful authentication.",
            "Report IDs and titles come only from the public catalog. Ordered report pairs require the same session and report with strictly increasing valid client timestamps; missing client times never become server-time sequences.",
            "Form acknowledgement provider results have no account/session/report linkage and remain site-wide, unattributed; provider acceptance is not inbox delivery.",
            "Public page/report breakdowns below the account threshold are omitted, not zero. Browser/device identities, raw queries and per-account rows are never exported.",
        ],
        "privacy": {"account_identifiers_included": False, "email_addresses_included": False,
                    "visitor_ids_included": False, "session_ids_included": False, "raw_queries_included": False},
    }


def markdown_summary(report: dict[str, Any]) -> str:
    lines = ["# 当前权限与窗口内活动汇总", "", f"区间：{report['start_date']} 至 {report['end_date']}（北京时间）。",
             f"权限快照：{report['snapshot_generated_at']}。有效权限不代表付费会员。", "",
             "| 当前权限组 | 账号数 | 可关联活动账号 | 登录身份主动活动账号 | 注册成功会话 | 下载成功会话 |",
             "| --- | ---: | ---: | ---: | ---: | ---: |"]
    for name, row in report["cohorts"].items():
        metrics = row["session_metrics"]
        lines.append(f"| {name} | {row['current_accounts']} | {row['observed_accounts']} | {row['authenticated_intentional_active_accounts']} | {metrics['registration_sessions']} | {metrics['download_success_sessions']} |")
    lines.extend(["", "## 当前不限量全站权限：窗口内最早可观察来源", "", "| 渠道 | 账号数 |", "| --- | ---: |"])
    primary = report["cohorts"][COHORTS[0]]
    for row in primary["earliest_observed_window_entry"]["channels"]:
        lines.append(f"| {row['channel']} | {row['accounts']} |")
    lines.extend(["", "## 报告活动", "", "| 公开报告 | 账号数 | 打开会话 | 下载成功会话 | 同报告先尝试后成功 |", "| --- | ---: | ---: | ---: | ---: |"])
    for row in primary["report_activity"]:
        title = row["title"].replace("|", "／").replace("\n", " ")
        lines.append(f"| {title} ({row['path']}) | {row['accounts']} | {row['report_open_sessions']} | {row['download_success_sessions']} | {row['ordered_attempt_then_success_sessions']} |")
    lines.extend(["", "## 关联覆盖", "", *[f"- {key}: {value}" for key, value in report["join_coverage"].items()], "", *report["notes"], ""])
    return "\n".join(lines)


def write_outputs(events: list[dict[str, Any]], snapshot_path: Path, catalog_path: Path | None,
                  start_date: str, end_date: str, output: Path, markdown_output: Path | None,
                  *, site_host: str = "", min_count: int = 2) -> dict[str, Any]:
    snapshot = json.loads(snapshot_path.read_text(encoding="utf-8"))
    catalog = json.loads(catalog_path.read_text(encoding="utf-8")) if catalog_path else []
    report = build_member_cohort(events, snapshot, start_date, end_date, catalog=catalog, site_host=site_host, min_count=min_count)
    growth.validate_aggregate_review(report)
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(json.dumps(report, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    if markdown_output:
        markdown_output.parent.mkdir(parents=True, exist_ok=True)
        markdown_output.write_text(markdown_summary(report), encoding="utf-8")
    return report
